S_CAP = doc.ensure_run_style(size=9, font="함초롬돋움", color="#595959")
S_TIP = doc.ensure_run_style(size=10, font="함초롬돋움", color="#1F4E79")

def last(): return len(doc.paragraphs) - 1
def fmt(**kw): doc.set_paragraph_format(paragraph_index=last(), **kw)
def P(text, style=S_BODY, **kw):
    p = doc.add_paragraph("", char_pr_id_ref=style, include_run=False)
    for i, part in enumerate(text.split("**")):
        if part: p.add_run(part, char_pr_id_ref=(S_BOLD if i % 2 else style))
    fmt(line_spacing_percent=160, **kw); return p
def H1(text, page_break=True): P(text, S_H1, spacing_before_pt=6, spacing_after_pt=6, page_break_before=page_break, bottom_border=True, border_color="#1F4E79")
def H2(text): P(text, S_H2, spacing_before_pt=8, spacing_after_pt=2)
def B(text): P("  ○ " + text, indent_left_mm=4)
def N(i, text): P(f"  {i}) " + text, indent_left_mm=4)
def TIP(text): P("※ " + text, S_TIP, spacing_after_pt=4)
def crop(name, box=None):
    im = Image.open(f"{IMG}/{name}").convert("RGB")
    if box: im = im.crop(box)
    b = io.BytesIO(); im.save(b, "PNG", optimize=True); return b.getvalue(), im.size
def pics(items, width_mm, caption):
    p = doc.add_paragraph("", include_run=False)
    for name, box in items:
        data, (w, h) = crop(name, box); item = doc.add_image(data, "png")
        W = round(width_mm * MM); p.add_picture(item, width=W, height=round(W * h / w), treat_as_char=True)
        p.add_run("   ", char_pr_id_ref=S_CAP)
    fmt(alignment="CENTER", spacing_before_pt=4)
    P(caption, S_CAP, alignment="CENTER", spacing_after_pt=6)
def table(rows, widths, shade="#D9E2F3"):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    for r, row in enumerate(rows):
        for c, v in enumerate(row):
            t.set_cell_text(r, c, v)
            if r == 0: t.set_cell_shading(r, c, shade)
    t.set_column_widths(widths)
    doc.add_paragraph("", char_pr_id_ref=S_CAP)
    return t
